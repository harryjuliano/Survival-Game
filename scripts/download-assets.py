"""Download verified CC0 assets for offline runtime use; no API access in the game."""
import urllib.request,json,pathlib,concurrent.futures,hashlib
ROOT=pathlib.Path(__file__).resolve().parents[1];OUT=ROOT/'public/assets';CACHE=ROOT/'asset-sources/metadata';CACHE.mkdir(parents=True,exist_ok=True);manifest=[];jobs=[]
def metadata(name):
 f=CACHE/(name+'.json')
 if not f.exists():
  req=urllib.request.Request('https://api.polyhaven.com/files/'+name,headers={'User-Agent':'RoomDecor3D-AssetPreparation/2.0'});f.write_bytes(urllib.request.urlopen(req,timeout=60).read())
 return json.loads(f.read_text())
for alias,id in {'sand':'coast_sand_02','grass':'grass_ground','wood':'brown_planks_03','plaster':'grey_plaster','roof':'clay_roof_tiles','bark':'bark_brown_02'}.items():
 d=metadata(id)
 for key,slot in [('Diffuse','color'),('nor_gl','normal'),('Rough','roughness')]:
  variants=d[key]['1k'];desc=variants.get('jpg') or variants.get('png');ext=desc['url'].rsplit('.',1)[1];jobs.append((desc,OUT/'textures'/alias/(slot+'.'+ext)))
 manifest.append({'name':id,'local':'textures/'+alias,'source':'https://polyhaven.com/a/'+id,'license':'CC0-1.0'})
id='kloofendal_48d_partly_cloudy_puresky';d=metadata(id);jobs.append((d['hdri']['1k']['hdr'],OUT/'environment/sky.hdr'));manifest.append({'name':id,'local':'environment/sky.hdr','source':'https://polyhaven.com/a/'+id,'license':'CC0-1.0'})
for id in ['island_tree_01','fern_02','coast_rocks_02','lambis_shell','sofa_03']:
 d=metadata(id)['gltf']['1k']['gltf'];dest=ROOT/'asset-sources'/id;jobs.append((d,dest/(id+'.gltf')))
 for path,desc in d.get('include',{}).items():jobs.append((desc,dest/path))
 manifest.append({'name':id,'local':'models/'+id+'.glb','source':'https://polyhaven.com/a/'+id,'license':'CC0-1.0','changes':'Texture resolution 1K; geometry optimized and LOD generated by build-assets.mjs.'})
def fetch(job):
 desc,path=job;path.parent.mkdir(parents=True,exist_ok=True)
 if path.exists() and hashlib.md5(path.read_bytes()).hexdigest()==desc.get('md5'):return
 for attempt in range(3):
  try:
   with urllib.request.urlopen(desc['url'],timeout=120) as r,open(str(path)+'.part','wb') as f:
    while b:=r.read(1024*1024):f.write(b)
   temp=pathlib.Path(str(path)+'.part');data=temp.read_bytes()
   if desc.get('md5') and hashlib.md5(data).hexdigest()!=desc['md5']:raise ValueError('Checksum mismatch')
   temp.replace(path);print(path.name,len(data),flush=True);return
  except Exception as e:
   if attempt==2:raise
with concurrent.futures.ThreadPoolExecutor(6) as ex:list(ex.map(fetch,jobs))
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2));print('All asset downloads verified.',flush=True)
